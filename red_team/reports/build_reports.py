BADGES = [
    ("CONFIRMED VULNERABILITY", "b-bad"), ("CONFIRMED", "b-bad"),
    ("DEFENSE HELD", "b-ok"), ("TESTED - NOT VULNERABLE", "b-ok"), ("PASS (secure)", "b-ok"),
    ("NOT APPLICABLE", "b-mut"), ("NOT TESTED", "b-mut"), ("INCONCLUSIVE", "b-mid"),
    ("UNVERIFIED", "b-mid"), ("BLOCKED", "b-mid"),
]


def badgify(hhtml):
    for text, cls in BADGES:
        hhtml = re.sub(re.escape(text),
                       f'<span class="badge {cls}">{text}</span>', hhtml)
    return hhtml


def render(md_text, title, landscape=False):
    body = markdown.markdown(md_text, extensions=["tables", "fenced_code", "toc", "sane_lists"])
    body = badgify(body)
    body_class = ' class="landscape"' if landscape else ""
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{_html.escape(title)} — SecureShop Red Team</title><style>{CSS}</style></head>
<body{body_class}><div class="cover"><div class="wrap"><div class="tag">CET431 · Red Team</div>
<h1>{_html.escape(title)}</h1>
<div class="meta">SecureShop Security Assessment · 2026-11-22</div></div></div>
<div class="wrap">{body}
<div class="footer">SecureShop Red Team · local authorized assessment · generated from
<code>red_team/reports/</code></div></div></body></html>"""


def main():
    built = []
    for src, name, title, landscape in REPORTS:
        p = (HERE / src).resolve()
        if not p.is_file():
            print("skip (missing):", src)
            continue
        out = HTML_DIR / f"{name}.html"
        out.write_text(render(p.read_text(encoding="utf-8"), title, landscape), encoding="utf-8")
        built.append((name, title))
        print("built", out.name)

    cards = "".join(
        f'<div class="card"><h3>{_html.escape(t)}</h3>'
        f'<a href="html/{n}.html">HTML</a> · <a href="pdf/{n}.pdf">PDF</a></div>'
        for n, t in built)
    index = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>SecureShop Red Team — Reports</title><style>{CSS}</style></head>
<body><div class="cover"><div class="wrap"><div class="tag">CET431 · Red Team</div>
<h1>SecureShop — Security Assessment Reports</h1>
<div class="meta">Index · 2026-11-22 · local authorized assessment</div></div></div>
<div class="wrap"><p>Professional reports generated from the Red Team markdown sources.
PDFs are produced by <code>build_reports.bat</code> (Edge headless).</p>
<div class="cards">{cards}</div>
<h2>Evidence</h2><ul>
<li><code>red_team/evidence/live/</code> — live regression results</li>
<li><code>red_team/evidence/naive_shop/</code> — naive attack results</li>
<li><code>red_team/reports/bandit_results.json</code>, <code>pip_audit.json</code> — raw tool output</li>
</ul>
<div class="footer">Open a report, then Ctrl+P → Save as PDF if the pdf/ files are not present.</div>
</div></body></html>"""
    (HERE / "index.html").write_text(index, encoding="utf-8")
    print("built index.html with", len(built), "reports")


if __name__ == "__main__":
    main()
